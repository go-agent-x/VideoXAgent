_thinking_started = False  # Track whether the thinking emoji has been printed
_current_model_name = "unknown"  # Current model name used when saving transcripts

def print_stream_event(event: dict, verbose: bool = True):
    """Process astream_events events and print plain text as it streams."""
    global _thinking_started
    kind = event.get("event", "")
    name = event.get("name", "")
    data = event.get("data", {})

    if kind == "on_chat_model_stream":
        # Stream of tokens generated by the LLM
        chunk = data.get("chunk")
        if chunk:
            # Check reasoning_content from OpenAI reasoning models, possibly in additional_kwargs
            additional_kwargs = getattr(chunk, 'additional_kwargs', {}) or {}
            reasoning_content = additional_kwargs.get('reasoning_content', '')
            if reasoning_content:
                if not _thinking_started:
                    print("💭 Reasoning: ", end="", flush=True)
                    _thinking_started = True
                print(reasoning_content, end="", flush=True)

            content = getattr(chunk, "content", "")
            # Content can be a string or a list, such as Claude thinking blocks
            if isinstance(content, str) and content:
                print(content, end="", flush=True)
            elif isinstance(content, list):
                # Handle the [{'thinking': 'xxx', 'type': 'thinking', 'index': 0}, ...] format
                for item in content:
                    if isinstance(item, dict):
                        item_type = item.get("type", "")
                        # Thinking/reasoning content in supported formats
                        # Claude: type="thinking", field="thinking"
                        # OpenAI o-series: type="reasoning" or "reasoning_content", field="content"/"text"/"reasoning_content"
                        # DeepSeek: type="reasoning_content", field="reasoning_content"
                        if item_type in ("thinking", "reasoning", "reasoning_content", "thought"):
                            thinking_text = (
                                item.get("thinking") or
                                item.get("reasoning_content") or
                                item.get("reasoning") or
                                item.get("thought") or
                                item.get("content") or
                                item.get("text") or
                                ""
                            )
                            if thinking_text:
                                # Print the emoji when thinking output starts
                                if not _thinking_started:
                                    print("💭 Thinking: ", end="", flush=True)
                                    _thinking_started = True
                                print(thinking_text, end="", flush=True)
                        # Plain text content
                        elif item.get("type") == "text":
                            text = item.get("text", "")
                            if text:
                                # Insert a newline when switching from thinking to text
                                if _thinking_started:
                                    print("\n\n📝 Response: ", end="", flush=True)
                                    _thinking_started = False
                                print(text, end="", flush=True)
                        # Start of tool_use
                        elif item.get("type") == "tool_use":
                            tool_name = item.get("name", "unknown")
                            if _thinking_started:
                                print()  # Insert a newline
                                _thinking_started = False
                            print(f"\n🔧 Calling: {tool_name}", flush=True)
                    elif isinstance(item, str):
                        print(item, end="", flush=True)

    elif kind == "on_tool_start":
        tool_name = name
        tool_input = data.get("input", {})
        print(f"\n🔧 Tool: {tool_name}", flush=True)
        # Truncate long inputs
        input_str = json.dumps(tool_input, ensure_ascii=False) if isinstance(tool_input, dict) else str(tool_input)
        if len(input_str) > 400:
            input_str = input_str[:400] + "..."
        print(f"   Input: {input_str}", flush=True)
        # Log all arguments to help debug missing arguments
        logger.info(f"Tool call: {tool_name} with full args: {json.dumps(tool_input, ensure_ascii=False) if isinstance(tool_input, dict) else tool_input}")

    elif kind == "on_tool_end":
        output = data.get("output", "")
        output_str = str(output)
        if len(output_str) > 600:
            output_str = output_str[:600] + "..."
        print(f"   ✅ Output: {output_str}", flush=True)

    elif kind == "on_tool_error":
        error = data.get("error", "")
        tool_input = data.get("input", {})
        # Print the full tool name, arguments, and error details for debugging
        print(f"   ❌ Tool Error: {name}", flush=True)
        print(f"   ❌ Args: {json.dumps(tool_input, ensure_ascii=False) if isinstance(tool_input, dict) else tool_input}", flush=True)
        print(f"   ❌ Error: {error}", flush=True)
        logger.error(f"Tool error: {name} with args: {json.dumps(tool_input, ensure_ascii=False) if isinstance(tool_input, dict) else tool_input}, error: {error}")

# Global state used for cleanup during signal handling
_session_manager = None
_cleanup_done = False


def _cleanup_mcp_sessions():
    """Clean up MCP sessions for both signal handlers and atexit."""
    global _session_manager, _cleanup_done
    if _cleanup_done or _session_manager is None:
        return
    _cleanup_done = True
    try:
        print("\n🧹 Cleaning up MCP sessions...")
        # Create an event loop if none is running during signal handling
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
        loop.run_until_complete(_session_manager.cleanup())
        print("✅ MCP sessions cleaned up")
    except Exception as e:
        print(f"⚠️ Error cleaning up MCP sessions: {e}")


def _signal_handler(signum, frame):
    """Handle termination signals."""
    sig_name = signal.Signals(signum).name
    print(f"\n⚠️ Received signal {sig_name}; exiting...")
    _cleanup_mcp_sessions()
    sys.exit(128 + signum)


# Register signal handlers
signal.signal(signal.SIGTERM, _signal_handler)
signal.signal(signal.SIGINT, _signal_handler)

# Register atexit cleanup for normal termination
atexit.register(_cleanup_mcp_sessions)


def format_message_content(message):
    """Convert message content to displayable string."""
    parts = []
    tool_calls_processed = False

    # Handle main content
    if isinstance(message.content, str):
        parts.append(message.content)
    elif isinstance(message.content, list):
        # Handle complex content like tool calls (Anthropic format)
        for item in message.content:
            if item.get("type") == "text":
                parts.append(item["text"])
            elif item.get("type") == "tool_use":
                parts.append(f"\n🔧 Tool Call: {item['name']}")
                parts.append(f"   Args: {json.dumps(item['input'], indent=2)}")
                parts.append(f"   ID: {item.get('id', 'N/A')}")
                tool_calls_processed = True
    else:
        parts.append(str(message.content))

    # Handle tool calls attached to the message (OpenAI format) - only if not already processed
    if (
        not tool_calls_processed
        and hasattr(message, "tool_calls")
        and message.tool_calls
    ):
        for tool_call in message.tool_calls:
            parts.append(f"\n🔧 Tool Call: {tool_call['name']}")
            parts.append(f"   Args: {json.dumps(tool_call['args'], indent=2)}")
            parts.append(f"   ID: {tool_call['id']}")

    return "\n".join(parts)

def format_messages(messages):
    """Format and display a list of messages with Rich formatting."""
    for m in messages:
        msg_type = m.__class__.__name__.replace("Message", "")
        content = format_message_content(m)

        if msg_type == "Human":
            console.print(Panel(content, title="🧑 Human", border_style="blue"))
        elif msg_type == "AI":
            console.print(Panel(content, title="🤖 Assistant", border_style="green"))
        elif msg_type == "Tool":
            console.print(Panel(content, title="🔧 Tool Output", border_style="yellow"))
        else:
            console.print(Panel(content, title=f"📝 {msg_type}", border_style="white"))

def _message_to_entry(msg, session_id, timestamp):
    """Convert a LangChain message to Claude Code session JSONL entry."""
    msg_type = msg.__class__.__name__

    if msg_type == "HumanMessage":
        return {
            "type": "user",
            "message": {"role": "user", "content": msg.content},
            "timestamp": timestamp,
            "sessionId": session_id
        }

    elif msg_type == "AIMessage":
        # Ensure content is a list in Anthropic format
        if isinstance(msg.content, list):
            content = list(msg.content)
        elif msg.content:
            content = [{"type": "text", "text": msg.content}]
        else:
            content = []

        # Normalize content items: convert bare strings to {"type": "text", "text": "..."} format
        # This handles Gemini's inconsistent output where text parts may be bare strings
        normalized_content = []
        for item in content:
            if isinstance(item, str):
                # Bare string -> wrap in text block
                if item:  # Only add non-empty strings
                    normalized_content.append({"type": "text", "text": item})
            else:
                normalized_content.append(item)
        content = normalized_content

        # Fix tool_use items: in streaming mode, input may be empty but partial_json contains the actual args
        for item in content:
            if isinstance(item, dict) and item.get("type") == "tool_use":
                # If input is empty/missing but partial_json exists, parse it
                if not item.get("input") and item.get("partial_json"):
                    try:
                        item["input"] = json.loads(item["partial_json"])
                    except json.JSONDecodeError:
                        pass  # Keep empty input if parsing fails
                # Remove partial_json from output (not needed in final format)
                item.pop("partial_json", None)
                item.pop("caller", None)  # Also remove caller metadata
                item.pop("index", None)   # Remove index

        # Merge tool_calls not already present in content
        existing_ids = {c.get("id") for c in content if isinstance(c, dict) and c.get("type") == "tool_use"}
        for tc in getattr(msg, 'tool_calls', None) or []:
            if tc.get("id") not in existing_ids:
                content.append({
                    "type": "tool_use",
                    "id": tc.get("id", ""),
                    "name": tc["name"],
                    "input": tc.get("args", {})
                })

        # Extract model name and usage from response_metadata
        meta = getattr(msg, 'response_metadata', None) or {}
        model = meta.get('model', meta.get('model_id', meta.get('model_name', '')))
        # Fallback to global model name if not found in response_metadata
        if not model:
            model = _current_model_name

        # Extract token usage: prefer usage_metadata (new LangChain, works with streaming),
        # fall back to response_metadata.usage (legacy / non-streaming)
        usage_meta = getattr(msg, 'usage_metadata', None) or {}
        if usage_meta:
            input_details = usage_meta.get('input_token_details', {}) or {}
            usage = {
                "input_tokens": usage_meta.get('input_tokens', 0),
                "output_tokens": usage_meta.get('output_tokens', 0),
                "cache_read_input_tokens": input_details.get('cache_read', 0),
                "cache_creation_input_tokens": input_details.get('cache_creation', 0),
            }
        else:
            raw_usage = meta.get('usage', {}) or meta.get('token_usage', {}) or {}
            usage = {
                # Anthropic format: input_tokens/output_tokens
                # OpenAI format: prompt_tokens/completion_tokens
                "input_tokens": raw_usage.get('input_tokens', 0) or raw_usage.get('prompt_tokens', 0),
                "output_tokens": raw_usage.get('output_tokens', 0) or raw_usage.get('completion_tokens', 0),
                "cache_read_input_tokens": raw_usage.get('cache_read_input_tokens', 0),
                "cache_creation_input_tokens": raw_usage.get('cache_creation_input_tokens', 0),
            }

        return {
            "type": "assistant",
            "message": {
                "id": getattr(msg, 'id', '') or "",
                "role": "assistant",
                "content": content,
                "model": model,
                "usage": usage
            },
            "timestamp": timestamp,
            "sessionId": session_id
        }

    elif msg_type == "ToolMessage":
        content_val = msg.content if isinstance(msg.content, str) else json.dumps(msg.content, ensure_ascii=False, default=str)
        return {
            "type": "user",
            "message": {
                "role": "user",
                "content": [{
                    "type": "tool_result",
                    "tool_use_id": getattr(msg, 'tool_call_id', ''),
                    "content": content_val
                }]
            },
            "timestamp": timestamp,
            "sessionId": session_id
        }

    else:
        console.log(f"Unsupported message type: {msg_type}")
        raise ValueError(f"Unsupported message type: {msg_type}")

    return None


def _extract_vlm_usage_from_tool_content(content):
    if not content:
        return None
    parsed = None
    if isinstance(content, dict):
        parsed = content
    elif isinstance(content, str):
        try:
            parsed = json.loads(content)
        except json.JSONDecodeError:
            try:
                parsed = ast.literal_eval(content)
            except (ValueError, SyntaxError):
                return None
    if isinstance(parsed, list):
        for item in parsed:
            if not isinstance(item, dict):
                continue
            text = item.get("text")
            if not text:
                continue
            nested_usage = _extract_vlm_usage_from_tool_content(text)
            if nested_usage:
                return nested_usage
    if not isinstance(parsed, dict):
        return None
    usage = parsed.get("vlm_usage")
    if not isinstance(usage, dict):
        return None
    return usage


def _accumulate_vlm_usage_from_entry(entry, totals):
    if not entry or entry.get("type") != "user":
        return
    blocks = entry.get("message", {}).get("content", [])
    if not isinstance(blocks, list):
        return
    for block in blocks:
        if not isinstance(block, dict) or block.get("type") != "tool_result":
            continue
        usage = _extract_vlm_usage_from_tool_content(block.get("content"))
        if not usage:
            continue
        totals["total_input_tokens"] += usage.get("input_tokens", 0) or usage.get("total_input_tokens", 0) or 0
        totals["total_output_tokens"] += usage.get("output_tokens", 0) or usage.get("total_output_tokens", 0) or 0
        totals["tool_call_count"] += usage["calls"] if "calls" in usage else 1


def save_result_as_conversation(result, prompt, start_time=None, end_time=None, exp_name: str | None = None, accumulated_usage: dict | None = None, completed: str = "success"):
    """Save agent result in Claude Code compatible format for html_show visualization.

    Converts LangChain messages to Claude Code session JSONL format, then
    appends session info to conversations/video_agent.json (multi-process safe).

    Args:
        exp_name: Optional experiment name. If provided, saves to all_data_path_{exp_name}.json
        accumulated_usage: Optional pre-accumulated token usage from astream_events.
                          When using astream_events, message.response_metadata may not
                          contain usage info, so we capture it from on_chat_model_end events.
        completed: Execution status. "success" if agent completed normally,
                   "execute_error" if an exception occurred,
                   "exceed_recursion_count" if recursion limit was reached.
    """
    session_id = str(uuid.uuid4())
    now = datetime.now()
    start_time = start_time or now
    end_time = end_time or now
    messages = result.get("messages", [])

    conversations_dir = Path(os.environ.get("CONVERSATIONS_DIR", "conversations"))
    transcripts_dir = conversations_dir / "transcripts"
    transcripts_dir.mkdir(parents=True, exist_ok=True)

    # 1. Save messages as JSONL transcript (Claude Code session log format)
    # Use pre-accumulated usage if provided (from astream_events on_chat_model_end),
    # otherwise fall back to extracting from message response_metadata
    if accumulated_usage:
        total_input_tokens = accumulated_usage.get("input_tokens", 0)
        total_output_tokens = accumulated_usage.get("output_tokens", 0)
        total_cache_read_tokens = accumulated_usage.get("cache_read_input_tokens", 0)
        total_cache_write_tokens = accumulated_usage.get("cache_creation_input_tokens", 0)
    else:
        total_input_tokens = 0
        total_output_tokens = 0
        total_cache_read_tokens = 0
        total_cache_write_tokens = 0

    vlm_usage_totals = {
        "total_input_tokens": 0,
        "total_output_tokens": 0,
        "tool_call_count": 0,
    }

    # Compute per-message time interval so first msg = start_time, last msg = end_time
    total_secs = (end_time - start_time).total_seconds()
    msg_count = len(messages)
    interval = total_secs / max(msg_count - 1, 1) if msg_count > 0 else 0

    transcript_path = transcripts_dir / f"{session_id}.jsonl"
    with open(transcript_path, 'w', encoding='utf-8') as f:
        for i, msg in enumerate(messages):
            timestamp = (start_time + timedelta(seconds=interval * i)).isoformat()
            entry = _message_to_entry(msg, session_id, timestamp)
            if entry:
                f.write(json.dumps(entry, ensure_ascii=False, default=str) + '\n')
                _accumulate_vlm_usage_from_entry(entry, vlm_usage_totals)
                # Only accumulate from messages if accumulated_usage was not provided
                if not accumulated_usage and entry.get("type") == "assistant":
                    usage = entry["message"].get("usage", {})
                    total_input_tokens += usage.get("input_tokens", 0)
                    total_output_tokens += usage.get("output_tokens", 0)
                    total_cache_read_tokens += usage.get("cache_read_input_tokens", 0)
                    total_cache_write_tokens += usage.get("cache_creation_input_tokens", 0)

    # 2. Append session info to video_agent.json with file locking (multi-process safe)
    session_info = {
        "session_id": session_id,
        "transcript_path": str(transcript_path.resolve()),
        "init_user_query": prompt,
        "timestamp": start_time.isoformat(),
        "completed": completed,
        "usage": {
            "total_input_tokens": total_input_tokens,
            "total_output_tokens": total_output_tokens,
            "total_cache_read_tokens": total_cache_read_tokens,
            "total_cache_write_tokens": total_cache_write_tokens,
        },
        "vlm_usage": {
            "total_input_tokens": vlm_usage_totals["total_input_tokens"],
            "total_output_tokens": vlm_usage_totals["total_output_tokens"],
            "total_tokens": vlm_usage_totals["total_input_tokens"] + vlm_usage_totals["total_output_tokens"],
            "tool_call_count": vlm_usage_totals["tool_call_count"],
        }
    }

    # json_path = conversations_dir / "video_agent.json"
    if exp_name:
        json_path = conversations_dir / f"all_data_path_{exp_name}.json"
    else:
        json_path = conversations_dir / "all_data_path.json"
    lock_path = conversations_dir / ".video_agent.lock"

    with open(lock_path, 'w') as lf:
        fcntl.flock(lf, fcntl.LOCK_EX)
        try:
            data = {"sessions": []}
            if json_path.exists():
                with open(json_path, 'r', encoding='utf-8') as jf:
                    data = json.load(jf)
            data.setdefault("sessions", []).append(session_info)
            with open(json_path, 'w', encoding='utf-8') as jf:
                json.dump(data, jf, indent=2, ensure_ascii=False)
        finally:
            fcntl.flock(lf, fcntl.LOCK_UN)

    print(f"Conversation saved: {transcript_path}")
    print(f"Token usage: input={total_input_tokens}, output={total_output_tokens}, "
          f"cache_read={total_cache_read_tokens}, cache_write={total_cache_write_tokens}")
    print(f"VLM tool usage: input={vlm_usage_totals['total_input_tokens']}, "
          f"output={vlm_usage_totals['total_output_tokens']}, calls={vlm_usage_totals['tool_call_count']}")


async def main(prompt: str, config_path: str, system_prompt_pth: str, disabled_tools: list[str] | None = None, stream: bool = False):
    _key_config_path = Path(__file__).resolve().parent / "key.yaml"

    # Read API keys from key.yaml
    with open(_key_config_path, "r", encoding="utf-8") as _f:
        _key_config = yaml.safe_load(_f)

    if _key_config.get("LLM_API_KEY"):
        os.environ["ANTHROPIC_API_KEY"] = _key_config["LLM_API_KEY"]
        os.environ["OPENAI_API_KEY"] = _key_config["LLM_API_KEY"]
        os.environ["GOOGLE_API_KEY"] = _key_config["LLM_API_KEY"]  # For ChatGoogleGenerativeAI

    # Fallback: use VLM_API_KEY for Google if LLM_API_KEY not set
    if not os.environ.get("GOOGLE_API_KEY") and _key_config.get("VLM_API_KEY"):
        os.environ["GOOGLE_API_KEY"] = _key_config["VLM_API_KEY"]
    
    # If .mcp.json env is empty ({}) or unset, pass None to inherit the entire parent environment
    # If .mcp.json env has values, use only those variables without inheriting the parent environment
    if _key_config.get("VLM_API_KEY"):
        os.environ["VLM_API_KEY"] = _key_config["VLM_API_KEY"]

    # ---- Load model config EARLY (before MCP) to get vlm_model_name ----
    _model_config_path = Path(config_path)
    with open(_model_config_path, "r", encoding="utf-8") as _f:
        _model_config = yaml.safe_load(_f)

    # CLI exclusions add to the experiment's policy; they never replace it.
    _disabled_builtin_tools = merge_disabled_builtin_tools(
        _model_config.get("disabled_builtin_tools"), disabled_tools,
    )

    for key, value in (_model_config.get("env") or {}).items():
        if value is not None:
            os.environ[str(key)] = str(value)

    # Inject environment variables into the MCP config so every server can access API keys
    _mcp_json_file = _model_config.get("mcp_json_file", ".mcp.json")
    _mcp_config = load_mcp_config(_mcp_json_file)
    _inject_env = {
        k: v for k, v in [
            ("VLM_API_KEY", _key_config.get("VLM_API_KEY")),
            ("DINOX_API_KEY", _key_config.get("DINOX_API_KEY")),
            ("VLM_MODEL_NAME", _model_config.get("vlm_model_name")),
            ("VLM_API_URL", _model_config.get("VLM_API_URL")),
            ("VLM_ENABLE_THINKING", _model_config.get("VLM_ENABLE_THINKING")),
            ("VLM_MAX_TOKENS", _model_config.get("VLM_MAX_TOKENS")),
            ("CUDA_VISIBLE_DEVICES", os.environ.get("CUDA_VISIBLE_DEVICES")),
        ] if v
    }
    if _model_config.get("vlm_model_name"):
        print(f"[video-agent] VLM_MODEL_NAME will be injected to MCP: {_model_config['vlm_model_name']}")
    if os.environ.get("CUDA_VISIBLE_DEVICES"):
        print(f"[video-agent] CUDA_VISIBLE_DEVICES will be injected to MCP: {os.environ['CUDA_VISIBLE_DEVICES']}")
    for _srv in _mcp_config["mcpServers"].values():
        _env = _srv.setdefault("env", {})
        
        # Disable tool proxies when the main script uses a proxy
        _env['http_proxy'] = ''
        _env['https_proxy'] = ''
        for _k, _v in _inject_env.items():
            if _k not in _env:
                _env[_k] = _v

    # ---- Setup LLM model ----
    _model_cfg = dict(_model_config["model"])
    _provider = _model_cfg.pop("provider")

    # Create HTTP clients that bypass proxies for direct access to internal APIs
    # _http_client = httpx.Client(trust_env=False)
    # _async_http_client = httpx.AsyncClient(trust_env=False)

    if _provider == "ChatOpenAI":
        model = ChatOpenAIWithReasoning(
            **_model_cfg,
            # http_client=_http_client,
            # http_async_client=_async_http_client,
        )
    elif _provider == "ChatAnthropic":
        model = ChatAnthropic(
            **_model_cfg,
            # http_client=_http_client,
        )
    elif _provider == "ChatGoogleGenerativeAI":
        # Native Google Gemini SDK with support for thinking output
        model = ChatGoogleGenerativeAI(
            **_model_cfg,
        )
    else:
        raise ValueError(f"Unknown provider: {_provider}")

    # 🔄 API retry configuration, implemented in the astream_events loop
    # Avoid with_retry() because its wrapper does not preserve the BaseChatModel type
    retry_config = _model_config.get("retry", {})
    _api_max_retries = retry_config.get("max_retries", 5)
    _api_initial_wait = retry_config.get("initial_wait", 30.0)
    _api_max_wait = retry_config.get("max_wait", 180.0)
    print(f"🔄 API retry configuration: max_retries={_api_max_retries}, initial_wait={_api_initial_wait}s, max_wait={_api_max_wait}s")

    # Consecutive tool failure detection
    MAX_CONSECUTIVE_TOOL_FAILURES = _model_config.get("max_consecutive_tool_failures", 5)
    consecutive_tool_failures = 0

    # Set global model name for transcript saving
    global _current_model_name
    _current_model_name = _model_cfg.get("model", "unknown")

    # Read the optional system_prompt file; fall back to BASE_AGENT_PROMPT if it does not exist
    # _prompt_path = Path(__file__).resolve().parent / "SYSTEM_PROMPT.md"
    _prompt_path = Path(system_prompt_pth)
    system_prompt = _prompt_path.read_text(encoding="utf-8") if _prompt_path.exists() else None

    mcp_tools, session_manager, server_info = await _load_tools_from_config(_mcp_config)

    # Remove server name prefixes so the model sees the original tool names
    # With tool_name_prefix=True, langchain-mcp-adapters defaults to "server__toolname"
    # Support double underscores in langchain-mcp-adapters v0.1.x (server__toolname)
    # Support single underscores in langchain-mcp-adapters v0.2.x (server_toolname)
    # Keep the full name on conflicts
    seen = {}
    for t in mcp_tools:
        name = t.name
        if "__" in name:
            short = name.split("__")[-1]    # Support v0.1.x double underscores
        else:
            pos = name.find("_")
            if pos > 0 and "-" in name[:pos]:
                short = name[pos + 1:]     # Support v0.2.x single underscores
            else:
                short = name
        if short in seen:
            short = name        # Keep the full name on conflicts
        seen[short] = True
        t.name = short

    # Store the session manager globally for cleanup during signal handling
    global _session_manager
    _session_manager = session_manager

    # Read recursion_limit from the config (default: 125)
    recursion_limit_val = _model_config.get("recursion_limit", 125)
    # Whether to enable budget warnings (enabled by default)
    _enable_budget_warning = _model_config.get("enable_budget_warning", True)

    # 🔄 Use MemorySaver as the checkpointer to support resuming execution
    # Resume from the last interrupted state after retryable errors such as HTTP 429
    checkpointer = MemorySaver()
    thread_id = str(uuid.uuid4())  # Use a unique thread_id for each run

    agent = create_deep_agent(
        model=model,
        tools=mcp_tools,
        system_prompt=system_prompt,
        subagents=[],
        backend=FilesystemBackend(virtual_mode=False),
        disabled_builtin_tools=_disabled_builtin_tools,
        recursion_limit=recursion_limit_val,
        enable_budget_warning=_enable_budget_warning,
        checkpointer=checkpointer,
    )

    start_time = datetime.now()

    # Reset thinking state so each run displays events in order (thinking before tools)
    global _thinking_started
    _thinking_started = False

    # Accumulate token usage captured from on_chat_model_end events
    # With astream_events, response_metadata in the final result messages may lack usage data
    accumulated_usage = {
        "input_tokens": 0,
        "output_tokens": 0,
        "cache_read_input_tokens": 0,
        "cache_creation_input_tokens": 0,
    }

    # Use astream_events to capture intermediate states (thinking, token streams, tool calls, etc.)
    result = None
    collected_messages = []  # Messages collected incrementally from events for error recovery
    execution_error = None   # Record exceptions raised during execution
    is_recursion_error = False  # Track recursion limit errors (GraphRecursionError)
    recursion_count = 0

    # Collect messages incrementally, deduplicating by message ID in a dict
    # key = message.id or tool_call_id, value = message object
    _msg_by_id = {}
    # Collect tool results: key = tool_call_id, value = ToolMessage
    _tool_results_by_id = {}
    # Pending tool_calls from AIMessage objects, used to construct ToolMessage objects
    _pending_tool_calls = {}  # key = tool_call_id, value = {"name": ..., "args": ...}
    # Fixed ID for the human message, which may lack an ID in the stream
    _human_msg_key = "__human__"

    # 🔄 API retry loop for errors such as HTTP 429 RateLimitError
    # Preserve collected message traces across retries without altering the context
    # Use the checkpointer and thread_id to resume from a checkpoint
    api_retry_count = 0
    is_first_attempt = True  # Track whether this is the first attempt
    api_retry_exhausted = False  # Track whether API retries were exhausted
    last_api_error = None  # Keep the last API error for the final report
    config = {
        "recursion_limit": recursion_limit_val,
        "configurable": {"thread_id": thread_id},  # Associate the checkpoint with thread_id
    }

    while api_retry_count <= _api_max_retries:
        try:
            # Build input: pass all messages on the first attempt and resume from the checkpoint on retries
            if is_first_attempt:
                input_data = {
                    "messages": [
                        {
                            "role": "user",
                            "content": prompt,
                        }
                    ],
                }
            else:
                # Pass None on retries to let LangGraph resume from the checkpoint
                # Command(resume=None) triggers the resume_is_map bug in LangGraph 1.1.4
                # None has the same semantics as Command(resume=None) but avoids the buggy code path
                input_data = None

            async for event in agent.astream_events(
                input_data,
                config,
                version="v2",  # Use v2 of the events API
            ):
                # Print intermediate events as they arrive
                if stream:
                    print_stream_event(event, verbose=False)  # Restore this setting after debugging

                # === Incremental message collection ===
                # 1) Collect the complete messages list from on_chain_end as the most reliable source
                if event.get("event") == "on_chain_end":
                    chain_output = event.get("data", {}).get("output")
                    if isinstance(chain_output, dict) and "messages" in chain_output:
                        # Messages may be a list or wrapped in a LangGraph Overwrite object
                        # Overwrite.value contains the actual messages list
                        raw_msgs = chain_output["messages"]
                        if hasattr(raw_msgs, 'value'):  # Overwrite object
                            raw_msgs = raw_msgs.value
                        if not isinstance(raw_msgs, list):
                            continue  # Skip unrecognized values
                        # Update the deduplication dict with the full list, replacing previously collected partial messages
                        for msg in raw_msgs:
                            msg_type = msg.__class__.__name__
                            if msg_type == "HumanMessage":
                                key = getattr(msg, 'id', None) or _human_msg_key
                            elif msg_type == "AIMessage":
                                key = getattr(msg, 'id', None) or None
                            elif msg_type == "ToolMessage":
                                key = getattr(msg, 'tool_call_id', None) or getattr(msg, 'id', None) or None
                            else:
                                key = getattr(msg, 'id', None) or None
                            if key:
                                _msg_by_id[key] = msg

                # 2) Collect AIMessage objects with tool_calls from on_chat_model_end
                #    This captures completed LLM calls even when the chain does not finish normally
                if event.get("event") == "on_chat_model_end":
                    output = event.get("data", {}).get("output")
                    if output and isinstance(output, AIMessage):
                        msg_id = getattr(output, 'id', None)
                        if msg_id:
                            _msg_by_id[msg_id] = output
                        # Record tool_calls from this AIMessage to construct the corresponding ToolMessage objects
                        for tc in getattr(output, 'tool_calls', None) or []:
                            tc_id = tc.get("id")
                            if tc_id:
                                _pending_tool_calls[tc_id] = {"name": tc["name"], "args": tc.get("args", {})}

                # 3) Collect raw tool outputs from on_tool_end and construct ToolMessage objects
                #    The output from on_tool_end is not a ToolMessage and must be wrapped explicitly
                if event.get("event") == "on_tool_end":
                    tool_name = event.get("name", "")
                    tool_output = event.get("data", {}).get("output", "")
                    tool_input = event.get("data", {}).get("input", {})
                    # Find a matching tool_call_id in pending_tool_calls
                    # Match pending tool calls in invocation order
                    matched_tc_id = None
                    for tc_id, tc_info in _pending_tool_calls.items():
                        if tc_info["name"] == tool_name and tc_id not in _tool_results_by_id:
                            matched_tc_id = tc_id
                            break
                    if matched_tc_id:
                        tool_msg = ToolMessage(
                            content=str(tool_output) if not isinstance(tool_output, str) else tool_output,
                            tool_call_id=matched_tc_id,
                            name=tool_name,
                        )
                        _tool_results_by_id[matched_tc_id] = tool_msg
                        _msg_by_id[matched_tc_id] = tool_msg

                    # Consecutive tool failure detection
                    output_str = str(tool_output) if not isinstance(tool_output, str) else tool_output
                    if '"success": false' in output_str or '"success":false' in output_str:
                        consecutive_tool_failures += 1
                        if consecutive_tool_failures >= MAX_CONSECUTIVE_TOOL_FAILURES:
                            raise ConsecutiveToolFailureError(
                                f"{consecutive_tool_failures} consecutive tool failures (>= {MAX_CONSECUTIVE_TOOL_FAILURES}) "
                                f"(last tool: {tool_name}). Likely infrastructure issue."
                            )
                    else:
                        consecutive_tool_failures = 0

                # === Recursion depth tracking ===
                # Track recursion depth by counting each completed tool call
                if event.get("event") == "on_tool_end":
                    recursion_count += 1
                    if recursion_count >= recursion_limit_val:
                        print(f"\n⚠️ Recursion limit {recursion_limit_val} reached; stopping this run to avoid an infinite loop! "
                              f"({recursion_count} tool calls completed)", file=sys.stderr)
                        # Try to recover the last message from collected events as a partial result
                        break

                # === Token usage collection ===
                # Capture usage data when an LLM call ends
                if event.get("event") == "on_chat_model_end":
                    output = event.get("data", {}).get("output")
                    if output:
                        # Prefer usage_metadata, the current LangChain standard field populated after stream aggregation
                        usage_meta = getattr(output, 'usage_metadata', None) or {}
                        if usage_meta:
                            accumulated_usage["input_tokens"] += usage_meta.get('input_tokens', 0)
                            accumulated_usage["output_tokens"] += usage_meta.get('output_tokens', 0)
                            # Cache fields in usage_metadata may be nested under input_token_details
                            input_details = usage_meta.get('input_token_details', {}) or {}
                            accumulated_usage["cache_read_input_tokens"] += input_details.get('cache_read', 0)
                            accumulated_usage["cache_creation_input_tokens"] += input_details.get('cache_creation', 0)
                        else:
                            # Fall back to response_metadata for older versions or non-streaming calls
                            meta = getattr(output, 'response_metadata', None) or {}
                            raw_usage = meta.get('usage', {}) or meta.get('token_usage', {}) or {}
                            accumulated_usage["input_tokens"] += raw_usage.get('input_tokens', 0) or raw_usage.get('prompt_tokens', 0)
                            accumulated_usage["output_tokens"] += raw_usage.get('output_tokens', 0) or raw_usage.get('completion_tokens', 0)
                            accumulated_usage["cache_read_input_tokens"] += raw_usage.get('cache_read_input_tokens', 0)
                            accumulated_usage["cache_creation_input_tokens"] += raw_usage.get('cache_creation_input_tokens', 0)

                # === Final result capture ===
                # Capture the final result
                if event.get("event") == "on_chain_end" and event.get("name") == "LangGraph":
                    result = event.get("data", {}).get("output", {"messages": []})

            # Execution completed normally; exit the retry loop
            break

        except RETRYABLE_EXCEPTIONS as e:
            # 🔄 First check for non-retryable errors such as GraphRecursionError
            if isinstance(e, NON_RETRYABLE_EXCEPTIONS) or isinstance(e.__cause__, NON_RETRYABLE_EXCEPTIONS):
                import traceback
                error_detail = traceback.format_exc()
                execution_error = f"{type(e).__name__}: {e}"
                if isinstance(e, GraphRecursionError) or isinstance(e.__cause__, GraphRecursionError):
                    is_recursion_error = True
                print(f"\n❌ Non-retryable error: {execution_error}", file=sys.stderr)
                print(f"   Traceback:\n{error_detail}", file=sys.stderr)
                logger.error(f"Non-retryable error: {execution_error}\n{error_detail}")
                break

            # Retryable API errors such as HTTP 429 RateLimitError
            last_api_error = f"{type(e).__name__}: {e}"  # Preserve the original API error
            api_retry_count += 1
            if api_retry_count > _api_max_retries:
                # Retries exhausted; use last_api_error as the final error message
                api_retry_exhausted = True
                execution_error = f"API retries exhausted ({_api_max_retries} retries). Last error: {last_api_error}"
                print(f"\n❌ {execution_error}", file=sys.stderr)
                logger.error(f"API retry exhausted: {last_api_error}")
                break

            # Calculate the wait time using exponential backoff with jitter
            import random
            wait_time = min(_api_initial_wait * (2 ** (api_retry_count - 1)), _api_max_wait)
            jitter = random.uniform(0, min(wait_time * 0.2, 10))  # Up to 20% jitter, capped at 10 seconds
            actual_wait = wait_time + jitter

            # Print retry details to stderr without adding them to the context
            err_msg = str(e)[:200]
            print(f"\n⚠️ [API Retry {api_retry_count}/{_api_max_retries}] Encountered {type(e).__name__}", file=sys.stderr)
            if "rate limit" in err_msg.lower() or "429" in err_msg:
                print(f"   Reason: API rate limit reached", file=sys.stderr)
            print(f"   Retrying in {actual_wait:.1f}s...", file=sys.stderr)
            sys.stderr.flush()

            # Wait before retrying
            await asyncio.sleep(actual_wait)
            print(f"   🔄 Starting retry {api_retry_count} (resuming from checkpoint)...", file=sys.stderr)
            is_first_attempt = False  # Mark this as a retry so the next attempt resumes from the checkpoint

        except NON_RETRYABLE_EXCEPTIONS as e:
            # 🚫 Exit immediately on non-retryable errors such as GraphRecursionError
            import traceback
            error_detail = traceback.format_exc()
            execution_error = f"{type(e).__name__}: {e}"
            if isinstance(e, GraphRecursionError):
                is_recursion_error = True
            print(f"\n❌ Non-retryable error (e.g. GraphRecursionError): {execution_error}", file=sys.stderr)
            logger.error(f"Non-retryable error: {execution_error}\n{error_detail}")
            break

        except Exception as e:
            # Other non-retryable errors
            import traceback
            error_detail = traceback.format_exc()
            current_error = f"{type(e).__name__}: {e}"

            # If a retry fails (e.g. Command cannot resume) and a previous API error is available,
            # report the API error first because it is the root cause
            if last_api_error and not is_first_attempt:
                # Resuming failed, but the API error is the root cause
                execution_error = f"API retry failed. Original error: {last_api_error} (error while resuming: {current_error})"
                print(f"\n❌ API retry failed", file=sys.stderr)
                print(f"   Original API error: {last_api_error}", file=sys.stderr)
                print(f"   Error while resuming: {current_error}", file=sys.stderr)
            else:
                execution_error = current_error
                print(f"\n❌ Agent execution error: {execution_error}", file=sys.stderr)
                print(f"   Traceback:\n{error_detail}", file=sys.stderr)
            logger.error(f"Agent execution error: {execution_error}\n{error_detail}")
            break

    # Build the final result from the normal output, or fall back to collected intermediate messages
    if result is None:
        # Order incrementally collected messages by conversation sequence (Human → AI → Tool → AI → ...)
        if _msg_by_id:
            # Ensure the human message comes first
            ordered = []
            if _human_msg_key in _msg_by_id:
                ordered.append(_msg_by_id[_human_msg_key])
            elif HumanMessage(content=prompt) not in ordered:
                ordered.append(HumanMessage(content=prompt))
            # Iterate in insertion order (Python 3.7+ dict preserves insertion order, i.e., event stream chronology)
            for key, msg in _msg_by_id.items():
                if key != _human_msg_key:
                    ordered.append(msg)
            result = {"messages": ordered}
        elif collected_messages:
            result = {"messages": list(collected_messages)}
        else:
            result = {"messages": [HumanMessage(content=prompt)]}
    else:
        # On normal completion, result contains all messages; incremental collection still supplies missing usage
        # (No additional work is needed; accumulated_usage was updated during event streaming)
        pass

    # Append any execution error to the messages list
    if execution_error:
        error_msg = AIMessage(content=f"[EXECUTION ERROR] An error occurred during agent execution; this run did not complete successfully.\n\nError details: {execution_error}")
        result["messages"].append(error_msg)

    if stream:
        print()  # Insert a newline

    end_time = datetime.now()

    # print(format_messages(result["messages"]))

    # Determine the execution status
    if is_recursion_error:
        completed_status = "exceed_recursion_count"
    elif execution_error:
        completed_status = "execute_error"
    elif recursion_count >= recursion_limit_val:
        completed_status = "exceed_recursion_count"
    else:
        completed_status = "success"

    # Save result in Claude Code compatible format for html_show visualization
    exp_name = _model_config.get("exp_name")
    save_result_as_conversation(result, prompt, start_time, end_time, exp_name=exp_name, accumulated_usage=accumulated_usage, completed=completed_status)

    # with open("result.json", "w", encoding="utf-8") as f:
    #     f.write(json.dumps(result, ensure_ascii=False, default=str, indent=2) + '\n')

    # Clean up MCP sessions safely
    try:
        await session_manager.cleanup()
    except Exception as e:
        print(f"⚠️ Non-fatal warning during MCP session cleanup: {e}", file=sys.stderr)


def parse_args():
    parser = argparse.ArgumentParser(description="Video agent with MCP tools")
    parser.add_argument('-p', '--prompt', type=str, help='Prompt to send to the agent')
    parser.add_argument('-c', '--config', type=str, help='Path to experiment config YAML file')
    parser.add_argument('-sys', '--system_prompt', type=str, help='Path to system prompt MarkDown file')
    parser.add_argument(
        '--disable-tools',
        type=str,
        nargs='+',
        default=[],
        help='Additional built-in tools to disable, e.g. read_file write_file execute. '
             'Merged with YAML disabled_builtin_tools; does not disable MCP services.'
    )
    parser.add_argument(
        '--stream',
        action='store_true',
        help='Stream the reasoning process, including tool calls and intermediate results'
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()

    if not args.prompt:
        print("Error: -p/--prompt is required", file=sys.stderr)
        sys.exit(1)
    
    if not args.config:
        print("Error: -c/--config is required", file=sys.stderr)
        sys.exit(1)
    
    if not args.system_prompt:
        print("Error: -sys/--system_prompt is required", file=sys.stderr)
        sys.exit(1)

    asyncio.run(main(args.prompt, args.config, args.system_prompt, args.disable_tools, args.stream))

